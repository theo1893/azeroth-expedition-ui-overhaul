function HDLUI.SJQKA(num)
    if not SUPERWOW_VERSION then
        print("本功能需要SUPERWOW支持，SUPERWOW目前并未得到官方的正式认可，请谨慎使用！")
        return
    end
	local SJQKAsaveString = ImportFile("SJQKA") or ""
	if UnitExists("target") then
		local _,targetGuid = UnitExists("target")
		local targetName = UnitName("target")
		local targetPosition = GetRealZoneText()
		local targetPosition2 = GetSubZoneText()
		local timeNow = date("%H:%M")
		SetRaidTarget("target", 9-num)
		SJQKAsaveString  = SJQKAsaveString.."目标："..targetName.."|GUID："..targetGuid.."|位置："..targetPosition.."-"..targetPosition2.."|编号："..num.."|时间："..timeNow.."秒\n"
		ExportFile("SJQKA", SJQKAsaveString )
	end
end


--返回同组别的guid列表
function HDLUI.getSameTeamGuidList(currentGuid)
    local currentData = HDLUI.markToUid[currentGuid]
    if not currentData then
        return {}  -- 如果当前GUID不在列表中，返回空表
    end
    local currentGroup = currentData[2]
    local sameTeam = {}
    for guid, data in pairs(HDLUI.markToUid) do
        if data[2] == currentGroup then
            sameTeam[guid] = data[1]  -- 可能需要返回GUID和对应的位置或其他信息
        end
    end
    return sameTeam
end


function HDLUI.SJQKAmark()
    if not SUPERWOW_VERSION then
        print("本功能需要SUPERWOW支持，SUPERWOW目前并未得到官方的正式认可，请谨慎使用！")
        return
	end

	if UnitExists("target") then
		local _,listUGuid = UnitExists("target")
		if HDLUI.markToUid[listUGuid] and not GetRaidTargetIndex("target") then
			local sameTeamList =  HDLUI.getSameTeamGuidList(listUGuid)
			for guidString,markIndex in pairs(sameTeamList) do
				TargetUnit(guidString)
				SetRaidTarget(guidString, 9-markIndex)
			end
			TargetLastTarget()
		end
	end
end

-- 自动分配所有掉落物品给自己
function HDLUI.AutoLootAllToSelf()
    if not IsRaidLeader() and not IsRaidOfficer() then
        print("只有团队领袖/助理可使用此功能")
        return
    end

    if GetNumLootItems() > 0 then
        for i = 1, GetNumLootItems() do
            local texture, name, quantity = GetLootSlotInfo(i)
            if texture and name then
                -- 安全模式分配（需手动点击确认）
                GiveMasterLoot(i, UnitName("player"))
                -- 直接分配模式（需关闭确认窗口）
                -- DEFAULT_CHAT_FRAME.editBox:SetText(format("/run GiveMasterLoot(%d, '%s')", i, UnitName("player")))
                -- ChatEdit_SendText(DEFAULT_CHAT_FRAME.editBox)
            end
        end
    end
end


