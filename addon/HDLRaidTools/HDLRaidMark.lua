local buffidToString = {
	
	["冰"] = {17544, "大冰抗"},
	["暗"] = {17548, "大暗抗"},
	["奥"] = {17549, "大奥抗"},
	["火"] = {17543, "大火炕"},
	
}
function HDLCheckBuffID(type)
	local buffid, buffname = unpack(buffidToString[type])
	print("检查"..buffname.."的buffid:"..buffid)
	local namelist = {}
	for i = 1, 40 do
		local name = UnitName("raid"..i)
		if name then
			local hasbuff = false
			local j = 1
			while UnitBuff("raid"..i, j) do
				local _,_,spellid = UnitBuff("raid"..i, j)
				if spellid == buffid then
					hasbuff = true
					break
				end
				j = j + 1
			end
			if not hasbuff then
				table.insert(namelist, name)
			end
		end
	end

	--生成【以下玩家没有buffname:name1,name2,name3】的字符串
	local nameliststr = "以下玩家没有"..buffname..":"
	for i, v in ipairs(namelist) do
		if i == 1 then
			nameliststr = nameliststr..v
		else
			nameliststr = nameliststr..","..v
		end
	end
	--发送团队聊天，让playername跑
	SendChatMessage(nameliststr, "RAID")
end

